export type DcPolicySeed = {
  code: string;
  domain: DcDomain;
  title: string;
  description: string;
  ownerRole: DcRole;
  executorRole: DcRole | null;
  finalDecisionRole: DcRole;
  level: DcLevel;
  autonomyRule: string;
  thresholdType: string | null;
  thresholdValue: number | null;
  thresholdUnit: string | null;
  escalationRule: string;
  justificationRequired: boolean;
  recommendationRequired: boolean;
  evidenceRequired: boolean;
  ceoVisibility: DcCeoVisibility;
  visibilityScope: DcVisibilityScope;
  keywords: string[];
  examples: string[];
};

type SeedInput = Omit<
  DcPolicySeed,
  "justificationRequired" | "recommendationRequired" | "evidenceRequired"
> &
  Partial<
    Pick<
      DcPolicySeed,
      "justificationRequired" | "recommendationRequired" | "evidenceRequired"
    >
  >;

function p(partial: SeedInput): DcPolicySeed {
  return {
    ...partial,
    justificationRequired: partial.justificationRequired ?? partial.level !== "GREEN",
    recommendationRequired: partial.recommendationRequired ?? partial.level === "RED",
    evidenceRequired: partial.evidenceRequired ?? false,
  };
}

